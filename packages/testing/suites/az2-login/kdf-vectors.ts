// =============================================================================================
// THE SHARED SET — the vectors that bind the clients TO EACH OTHER, not each to itself.
// =============================================================================================
//
// Each client verifying composed==decomposed *in its own language* proves only that the client
// is self-consistent. What binds them is an agreed EXPECTED OUTPUT, and these three carry one.
//
// SV1 and SV2 arrived confirmed across four implementations — web's shipped `kdf.ts`, Apple's
// hand-written PBKDF2, Apple's `CCKeyDerivationPBKDF`, and a Python `hashlib.pbkdf2_hmac`. This
// file adds a fifth, `node:crypto`, and asserts the values rather than restating them.
//
// SV3 EXISTS BECAUSE SV2 IS BLIND TO THE DEFECT IT LOOKS LIKE IT COVERS, which is the most
// valuable thing anyone found in this slice. `ä` and `ö` have NO compatibility decomposition, so
// NFKC and NFC are the same function over `pässwörd` — SV2 passes with the two calls
// deliberately exchanged. Only a character that HAS a compatibility decomposition can tell them
// apart. Two defect classes, two vectors, neither substituting for the other:
//
//   a client skips normalisation entirely   -> SV2 (composed vs decomposed must MATCH)
//   a client uses NFKC where NFC belongs    -> SV3 (ligature vs plain must DIFFER)
//
