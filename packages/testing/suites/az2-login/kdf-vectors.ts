/**
 * ===========================================================================================
 * THE CROSS-CLIENT KDF VECTOR TABLE. `docs/decisions/0015` §D and its NFC amendment.
 * ===========================================================================================
 *
 * ONE CONTRACT SET, THREE IMPLEMENTATIONS: the web client (`platform/web/src/api/kdf.ts`), the
 * Apple client (Swift, not yet written), and the enrolment tool
 * (`platform/core/identity/tools/seed-principal.ts`), which derives the client value on the
 * operator's behalf and is therefore a client of this rule whatever directory it lives in.
 *
 * All three must produce BYTE-IDENTICAL output. `0015` states the consequence of divergence in
 * the plainest available terms: *"The user enrols on one platform and cannot log in on the
 * other, and the failure presents as a wrong password, which is the least diagnosable form it
 * could take."* Nothing stores a plaintext password, so a divergence discovered after enrolment
 * cannot be migrated — the account is simply gone.
 *
 * ===========================================================================================
 * EVERY NON-ASCII CHARACTER IN THIS FILE IS A `\uXXXX` ESCAPE. THIS IS NOT A STYLE CHOICE.
 * ===========================================================================================
 *
 * The whole point of the composed/decomposed pair is that the two are DIFFERENT BYTES that look
 * identical. A literal written into this file can be normalised by an editor, a copy-paste, a
 * clipboard, a git filter, or the tool that wrote it — and a decomposed vector that silently
 * became composed on disk still passes, while testing nothing at all. Escapes cannot be
 * normalised, so the vector on disk is the vector that was intended.
 *
 * `assertNormalisationFormsAreDistinct` below re-checks this at run time anyway, because a rule
 * that depends on a future editor's discipline is not a rule.
 *
 * ===========================================================================================
 * THE NORMATIVE RULE, RESTATED HERE BECAUSE THE VECTORS ARE ONLY MEANINGFUL BESIDE IT
 * ===========================================================================================
 *
 *   identifier  validate ASCII 0x21-0x7E, length 3-254, contains '@'  (whitespace REFUSED,
 *               never trimmed), then NFKC, then ASCII-ONLY case folding A-Z -> a-z
 *               (NOT `toLowerCase()`)
 *   password    NFC only. No case folding, no trimming, no ASCII restriction.
 *               RFC 8265 PRECIS `OpaqueString`.
 *   derivation  PBKDF2-SHA256(password_utf8, salt = normalised_identifier_utf8, 600000, 32)
 *   encoding    base64url, unpadded, exactly 43 characters
 *
 * ===========================================================================================
 * WHAT THE EXPECTED COLUMN IS, AND WHY IT IS NOT COMPUTED BY EITHER CLIENT
 * ===========================================================================================
 *
 * Every expected value is produced by `node:crypto`'s `pbkdf2Sync` — a different implementation
 * from the `crypto.subtle` both TypeScript clients use. A table generated by the web client and
 * then checked against the web client would agree with itself. `app-agent` should check Swift's
 * output against THIS reference, not against the web client's, for the same reason.
 */

