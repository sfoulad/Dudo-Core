/** The reference implementation. Independent of both clients by construction. */
export function referenceDerive(password: string, normalizedIdentifier: string): string {
  return toBase64Url(
    new Uint8Array(
      pbkdf2Sync(
        Buffer.from(password.normalize('NFC'), 'utf8'),
        Buffer.from(normalizedIdentifier, 'utf8'),
        ITERATIONS,
        OUTPUT_BYTES,
        'sha256',
      ),
    ),
  );
}

